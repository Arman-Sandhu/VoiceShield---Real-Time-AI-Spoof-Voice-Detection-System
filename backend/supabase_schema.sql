-- 1. Create table if it doesn't already exist
CREATE TABLE IF NOT EXISTS public.analysis_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id TEXT NOT NULL UNIQUE,
    user_id TEXT NOT NULL,
    mode TEXT NOT NULL,
    duration REAL,
    model_name TEXT,
    fake_score REAL,
    real_score REAL,
    prediction TEXT,
    context_risk JSONB,
    final_risk TEXT,
    risk_explanation TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Add new model and prediction columns if updating an existing table
ALTER TABLE public.analysis_history 
    ADD COLUMN IF NOT EXISTS model_name TEXT,
    ADD COLUMN IF NOT EXISTS fake_score REAL,
    ADD COLUMN IF NOT EXISTS real_score REAL,
    ADD COLUMN IF NOT EXISTS prediction TEXT,
    ADD COLUMN IF NOT EXISTS risk_explanation TEXT;

-- 3. Enable Row Level Security (RLS)
ALTER TABLE public.analysis_history ENABLE ROW LEVEL SECURITY;

-- 4. Fast lookup index for user isolation
CREATE INDEX IF NOT EXISTS idx_analysis_history_user_id ON public.analysis_history(user_id);

-- 5. Chronological ordering index
CREATE INDEX IF NOT EXISTS idx_analysis_history_created_at ON public.analysis_history(created_at DESC);
