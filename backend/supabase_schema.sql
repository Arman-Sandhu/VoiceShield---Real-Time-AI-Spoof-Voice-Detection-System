-- 1. Create the 'users' table to store user identity, joined time, and aggregate metrics
CREATE TABLE IF NOT EXISTS public.users (
    user_id TEXT PRIMARY KEY,
    email TEXT,
    joined_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    last_active_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    total_audios_analyzed INTEGER DEFAULT 0 NOT NULL,
    total_time_analyzed REAL DEFAULT 0.0 NOT NULL,     -- cumulative duration in seconds
    total_recorded INTEGER DEFAULT 0 NOT NULL,          -- audios recorded via microphone
    total_uploaded INTEGER DEFAULT 0 NOT NULL,          -- audios uploaded from file
    total_spoofs_detected INTEGER DEFAULT 0 NOT NULL,   -- AI generated/cloned voice detections
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Ensure all columns exist if upgrading an existing users table
ALTER TABLE public.users
    ADD COLUMN IF NOT EXISTS username TEXT DEFAULT '',
    ADD COLUMN IF NOT EXISTS email TEXT,
    ADD COLUMN IF NOT EXISTS joined_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
    ADD COLUMN IF NOT EXISTS last_active_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
    ADD COLUMN IF NOT EXISTS total_audios_analyzed INTEGER DEFAULT 0,
    ADD COLUMN IF NOT EXISTS total_time_analyzed REAL DEFAULT 0.0,
    ADD COLUMN IF NOT EXISTS total_recorded INTEGER DEFAULT 0,
    ADD COLUMN IF NOT EXISTS total_uploaded INTEGER DEFAULT 0,
    ADD COLUMN IF NOT EXISTS total_spoofs_detected INTEGER DEFAULT 0;

-- 2. Create the 'analysis_history' table partitioned by user subspace
CREATE TABLE IF NOT EXISTS public.analysis_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id TEXT NOT NULL UNIQUE,
    user_id TEXT NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    mode TEXT NOT NULL,                                 -- 'record' or 'upload'
    duration REAL DEFAULT 0.0,                          -- audio duration in seconds
    model_name TEXT,
    fake_score REAL,
    real_score REAL,
    prediction TEXT,                                    -- 'AI_GENERATED' or 'HUMAN_SPEECH'
    context_risk JSONB,
    final_risk TEXT,
    risk_explanation TEXT,
    file_name TEXT DEFAULT '',
    username TEXT DEFAULT '',
    user_email TEXT DEFAULT '',
    is_flagged BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Ensure all columns exist on analysis_history
ALTER TABLE public.analysis_history 
    ADD COLUMN IF NOT EXISTS model_name TEXT,
    ADD COLUMN IF NOT EXISTS fake_score REAL,
    ADD COLUMN IF NOT EXISTS real_score REAL,
    ADD COLUMN IF NOT EXISTS prediction TEXT,
    ADD COLUMN IF NOT EXISTS risk_explanation TEXT,
    ADD COLUMN IF NOT EXISTS file_name TEXT DEFAULT '',
    ADD COLUMN IF NOT EXISTS username TEXT DEFAULT '',
    ADD COLUMN IF NOT EXISTS user_email TEXT DEFAULT '',
    ADD COLUMN IF NOT EXISTS is_flagged BOOLEAN DEFAULT FALSE;

-- 3. Automatic backfill: Populate users table from any existing analysis_history records
INSERT INTO public.users (
    user_id, 
    email, 
    joined_at, 
    last_active_at, 
    total_audios_analyzed, 
    total_time_analyzed, 
    total_recorded, 
    total_uploaded, 
    total_spoofs_detected
)
SELECT 
    ah.user_id,
    MAX(ah.user_id) || '@voiceshield.internal' AS email,
    MIN(ah.created_at) AS joined_at,
    MAX(ah.created_at) AS last_active_at,
    COUNT(*)::INTEGER AS total_audios_analyzed,
    COALESCE(SUM(ah.duration), 0.0)::REAL AS total_time_analyzed,
    COUNT(*) FILTER (WHERE ah.mode = 'record')::INTEGER AS total_recorded,
    COUNT(*) FILTER (WHERE ah.mode != 'record')::INTEGER AS total_uploaded,
    COUNT(*) FILTER (WHERE ah.prediction = 'AI_GENERATED' OR COALESCE(ah.fake_score, 0) >= 0.5)::INTEGER AS total_spoofs_detected
FROM public.analysis_history ah
WHERE NOT EXISTS (
    SELECT 1 FROM public.users u WHERE u.user_id = ah.user_id
)
GROUP BY ah.user_id
ON CONFLICT (user_id) DO NOTHING;

-- 4. Foreign Key constraint safety (for existing tables without FK constraint)
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.table_constraints 
        WHERE constraint_name = 'fk_analysis_history_user' 
        AND table_name = 'analysis_history'
    ) THEN
        BEGIN
            ALTER TABLE public.analysis_history
                ADD CONSTRAINT fk_analysis_history_user
                FOREIGN KEY (user_id) REFERENCES public.users(user_id)
                ON DELETE CASCADE;
        EXCEPTION WHEN duplicate_object THEN
            -- Constraint already exists under another name
            NULL;
        END;
    END IF;
END $$;

-- 5. Trigger to automatically maintain user subspace statistics on every audio analysis
CREATE OR REPLACE FUNCTION public.sync_user_analysis_subspace()
RETURNS TRIGGER AS $$
DECLARE
    is_spoof BOOLEAN;
    is_rec BOOLEAN;
BEGIN
    IF (TG_OP = 'INSERT') THEN
        is_spoof := (NEW.prediction = 'AI_GENERATED' OR COALESCE(NEW.fake_score, 0) >= 0.5);
        is_rec := (NEW.mode = 'record');

        -- Upsert user record: creates subspace if first audio, or updates counters and profile
        INSERT INTO public.users (
            user_id,
            email,
            username,
            joined_at,
            last_active_at,
            total_audios_analyzed,
            total_time_analyzed,
            total_recorded,
            total_uploaded,
            total_spoofs_detected
        )
        VALUES (
            NEW.user_id,
            COALESCE(NEW.user_email, NEW.user_id || '@voiceshield.internal'),
            COALESCE(NEW.username, ''),
            NEW.created_at,
            NEW.created_at,
            1,
            COALESCE(NEW.duration, 0.0),
            CASE WHEN is_rec THEN 1 ELSE 0 END,
            CASE WHEN NOT is_rec THEN 1 ELSE 0 END,
            CASE WHEN is_spoof THEN 1 ELSE 0 END
        )
        ON CONFLICT (user_id) DO UPDATE SET
            last_active_at = NEW.created_at,
            email = COALESCE(NULLIF(public.users.email, ''), NEW.user_email, public.users.email),
            username = CASE WHEN COALESCE(NEW.username, '') <> '' THEN NEW.username ELSE public.users.username END,
            total_audios_analyzed = public.users.total_audios_analyzed + 1,
            total_time_analyzed = public.users.total_time_analyzed + COALESCE(NEW.duration, 0.0),
            total_recorded = public.users.total_recorded + (CASE WHEN is_rec THEN 1 ELSE 0 END),
            total_uploaded = public.users.total_uploaded + (CASE WHEN NOT is_rec THEN 1 ELSE 0 END),
            total_spoofs_detected = public.users.total_spoofs_detected + (CASE WHEN is_spoof THEN 1 ELSE 0 END);
        RETURN NEW;

    ELSIF (TG_OP = 'DELETE') THEN
        is_spoof := (OLD.prediction = 'AI_GENERATED' OR COALESCE(OLD.fake_score, 0) >= 0.5);
        is_rec := (OLD.mode = 'record');

        UPDATE public.users SET
            total_audios_analyzed = GREATEST(0, total_audios_analyzed - 1),
            total_time_analyzed = GREATEST(0.0, total_time_analyzed - COALESCE(OLD.duration, 0.0)),
            total_recorded = GREATEST(0, total_recorded - (CASE WHEN is_rec THEN 1 ELSE 0 END)),
            total_uploaded = GREATEST(0, total_uploaded - (CASE WHEN NOT is_rec THEN 1 ELSE 0 END)),
            total_spoofs_detected = GREATEST(0, total_spoofs_detected - (CASE WHEN is_spoof THEN 1 ELSE 0 END))
        WHERE user_id = OLD.user_id;
        RETURN OLD;
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Bind trigger to analysis_history
DROP TRIGGER IF EXISTS trg_sync_user_analysis_subspace ON public.analysis_history;
CREATE TRIGGER trg_sync_user_analysis_subspace
AFTER INSERT OR DELETE ON public.analysis_history
FOR EACH ROW EXECUTE FUNCTION public.sync_user_analysis_subspace();

-- 6. Row Level Security (RLS) policies for complete user subspace isolation
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.analysis_history ENABLE ROW LEVEL SECURITY;

-- Allow full access to backend service role (SUPABASE_SERVICE_KEY)
-- and isolate user records strictly to their own UID
DROP POLICY IF EXISTS "Users can view and manage their own profile" ON public.users;
CREATE POLICY "Users can view and manage their own profile"
    ON public.users
    FOR ALL
    USING (auth.uid()::text = user_id OR auth.role() = 'service_role')
    WITH CHECK (auth.uid()::text = user_id OR auth.role() = 'service_role');

DROP POLICY IF EXISTS "Users can view and manage their own analysis history" ON public.analysis_history;
CREATE POLICY "Users can view and manage their own analysis history"
    ON public.analysis_history
    FOR ALL
    USING (auth.uid()::text = user_id OR auth.role() = 'service_role')
    WITH CHECK (auth.uid()::text = user_id OR auth.role() = 'service_role');

-- 7. Performance Indexes for Subspace Lookups
CREATE INDEX IF NOT EXISTS idx_users_user_id ON public.users(user_id);
CREATE INDEX IF NOT EXISTS idx_analysis_history_user_id ON public.analysis_history(user_id);
CREATE INDEX IF NOT EXISTS idx_analysis_history_user_created ON public.analysis_history(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_analysis_history_user_mode ON public.analysis_history(user_id, mode);

